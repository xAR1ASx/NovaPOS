/// Catálogo Maestro de Productos precargados para Fruvers y Minimarkets en Colombia.
/// Contiene ~120 referencias altamente comercializadas con códigos PLU,
/// categorías oficiales, estimación de costos/precios y banderas de pesaje.

class ProductoMaestro {
  final String nombre;
  final String categoria;
  final String codigoPlu;
  final String codigoBarras;
  final double precioCosto;
  final double precioVenta;
  final int esPesable; // 1: Por Kg / Báscula, 0: Por unidad
  final String uuid;
  final String? imagenPath;
  final int esFavorito;

  const ProductoMaestro({
    required this.nombre,
    required this.categoria,
    required this.codigoPlu,
    this.codigoBarras = '',
    required this.precioCosto,
    required this.precioVenta,
    required this.esPesable,
    required this.uuid,
    this.imagenPath,
    this.esFavorito = 0,
  });

  Map<String, dynamic> toMap() {
    return {
      'nombre': nombre,
      'categoria': categoria,
      'codigo_plu': codigoPlu,
      'codigo_barras': codigoBarras,
      'precio_costo': precioCosto,
      'precio_venta': precioVenta,
      'stock_actual': 0.0,
      'es_pesable': esPesable,
      'esta_activo': 1,
      'uuid': uuid,
      'imagen_path': imagenPath ?? 'assets/catalogo/$uuid.jpg',
      'es_favorito': esFavorito,
    };
  }
}

